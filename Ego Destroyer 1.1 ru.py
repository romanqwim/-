def показать_вопрос(вопрос: Вопрос, ответ: str, фраза: str) -> None:
    """Показывает вопрос и реакцию на него."""
    print(f"\n😎 {фраза.upper()}! Ты ответил(а) '{ответ.upper()}' на вопрос:")
    print(f"👉 \"{вопрос.текст}\"")
    print("-" * 50 + "\n")

def обработать_ответ(вопрос: Вопрос, ответ: str, фразы: List[str]) -> int:
    """
    Обрабатывает ответ пользователя и возвращает результат.
    Возвращает 1, если самооценка была разрушена, иначе 0.
    """
    фраза = random.choice(фразы)
    показать_вопрос(вопрос, ответ, фраза)
    
    # Обработка особых случаев
    if вопрос.это_контракт:
        обработать_контракт_души()
        return 1
    
    # Обработка продолжения для IQ
    if вопрос.требует_продолжение and ответ == "нет":
        print(обработать_продолжение_iq(ответ))
        return 1
    
    # Обычный ответ
    print(вопрос.получить_ответ(ответ))
    print("-" * 50 + "\n")
    return 1

