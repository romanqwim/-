import random
import time

def игра_перевертыш():
    # ✍️ СПИСОК ВОПРОСОВ
    список_вопросов = [
        "Ты кушал(а) стиральный порошок?", 
        "твой iq ниже комнатной температуры?", 
        "ты пользвался(ась) мозгами?",
        "сосал(а)?", 
        "ты спал(а) с соседкой(ом)?", 
        "ты любишь облизывать асвальт?", 
        "у тебя будет понос?",
        "ты туг туг сахар?", 
        "готов(а) сьесть кошачий корм?", 
        "засунешь свои пальци в розетку за 15₽?", 
        "продашь душу за пкачку скитолс и 3₽", 
        "скушаешь использванную жвачку?", 
        "пробвал мытся"
    ]
    
    while True:
        # ПРОВЕРКА: Если вопросы закончились, закрываем игру
        if not список_вопросов:
            print("🎉 Пиздец, ты ответил на все вопросы! Список пуст, расходимся.")
            break

        # ШАГ 1: Ввод ответа
        ответ = input("сюды вписывай да или нет или стоп ").lower().strip()
        
        # Проверка на выход
        if ответ == "стоп":
            print("\n Давай иди нахуй от сюда я даже рад этому!")
            break
            
        # Проверяем корректность ввода
        elif ответ == "да" or ответ == "нет":
            print("\n[Анализирую твой ответ...]")
            time.sleep(1) # Короткая пауза для интриги
            
            # ШАГ 2: Выбираем случайный вопрос и СРАЗУ УДАЛЯЕМ его из списка (.pop)
            случайный_вопрос = список_вопросов.pop(random.randint(0, len(список_вопросов) - 1))
            
            # ШАГ 3: Вывод вопроса
            print(f"\n я думаю у тебя есть память на то чтобы запомнить как ты ответил но для красаты напишу твой ответ '{ответ.upper()}' на вопрос:")
            print(f"👉 \"{случайный_вопрос}\"")
            print("-" * 40 + "\n")
            
            # =========================================================================
            # УНИКАЛЬНЫЕ ОТВЕТЫ ДЛЯ КАЖДОГО ВОПРОСА:
            # =========================================================================

            # 1. Стиральный порошок
            if случайный_вопрос == "Ты кушал(а) стиральный порошок?":
                if ответ == "да":
                    print("Пиздец, у тебя внутри походу уже режим отжима включился 🧼\n")
                else:
                    print("А чё так? Попробуй, хоть изнутри от грязи отмоешься, чушка.\n")

            # 2. IQ ниже комнатной
            elif случайный_вопрос == "твой iq ниже комнатной температуры?":
                if ответ == "нет":
                    подколка = input("Значит ещё ниже? (да/нет): ").lower().strip()
                    if подколка == "да":
                        print("\nНу вот, сам(а) признался(ась)! Настоящий гений. 😂\n")
                    elif подколка == "нет":
                        print("\nОтрицание — первая стадия принятия, расслабься. 😏\n")
                    else:
                        print("\nДаже тут нормально ответить не можешь, походу реально ниже...\n")
                else:
                    print("Самокритично! Уважаю за честность. 😂\n")

            # 3. Пользовался мозгами
            elif случайный_вопрос == "ты пользвался(ась) мозгами?":
                if ответ == "да":
                    print("пока не доказано не ебет что сказано 😂\n")
                else:
                    print("по тебе видно 😏\n")

            # 4. Сосал(а)
            elif случайный_вопрос == "сосал(а)?":
                if ответ == "да":
                    print("Ну ты и заглотыш, стаж большой уже? 👄\n")
                else:
                    print("Не пизди, по губам же видно, что со стажем.\n")

            # 5. Спал с соседкой/соседом
            elif случайный_вопрос == "ты спал(а) с соседкой(ом)?":
                if ответ == "да":
                    print("Ну ты и блядина, а если за стенкой услышат? 🚪\n")
                else:
                    print("Конечно не спал(а), тебя туда даже за доплату не пустят.\n")

            # 6. Облизывать асфальт
            elif случайный_вопрос == "ты любишь облизывать асвальт?":
                if ответ == "да":
                    print("Губной гурман хуев. Как на вкус, камни с грязью заходят? 🛣️\n")
                else:
                    print("Жаль, а я думал ты местный пылесос дорожный.\n")

            # 7. Будет понос
            elif случайный_вопрос == "у тебя будет понос?":
                if ответ == "да":
                    print("Удачи добежать, штаны сменные хоть приготовил(а)? 💩\n")
                else:
                    print("Будет-будет, я туда уже слабительного подсыпал.\n")

            # 8. Туг туг сахар
            elif случайный_вопрос == "ты туг туг сахар?":
                if ответ == "да":
                    print("Ебать ты сладкий(ая), аж приторно стало 🍬\n")
                else:
                    print("Ты не сахар, ты унылое говно без фантазии.\n")

            # 9. Кошачий корм
            elif случайный_вопрос == "готов(а) сьесть кошачий корм?":
                if ответ == "да":
                    print("Вискас или Китикет? Смотри не замурчи там от удовольствия, животное 🐱\n")
                else:
                    print("А зря, судя по твоему лицу, это твоя основная диета.\n")

            # 10. Пальцы в розетку за 15 рублей
            elif случайный_вопрос == "засунешь свои пальци в розетку за 15₽?":
                if ответ == "да":
                    print("Ебать ты дешевка, тебя за сотку походу вообще можно в рабство купить ⚡\n")
                else:
                    print("Правильно, копи сразу 20 рублей, бизнесмен хуев.\n")

            # 11. Продажа души за Скитлс
            elif случайный_вопрос == "продашь душу за пкачку скитолс и 3₽":
                print("📜 ВНИМАНИЕ! Сгенерирован официальный ДОГОВОР купли-продажи души:")
                print("=" * 50)
                print("Я, нижеподписавшийся лох, обязуюсь передать свою")
                print("бессмертную душу в обмен на 1 пачку Skittles")
                print("и денежные средства в размере 3 рублей 00 копеек.")
                print("=" * 50)
                
                input("✒️ Оставьте вашу электронную подпись (введите имя): ")
                
                while True:
                    финал = input("\nВы подтверждаете условия контракта КРОВЬЮ? (да/нет): ").lower().strip()
                    if финал == "да":
                        print("\n😈 Контракт подписан! Skittles уже в пути, за душой придем в полночь.\n")
                        break
                    elif финал == "нет":
                        print("\n😒 Сделка сорвалась в последний момент ну ты и ублюдок… деньги за бумагу верни\n")
                        break
                    else:
                        print("блять какая же ты хуевина, напиши да или нет но лучше да")

            # 12. Использованная жвачку
            elif случайный_вопрос == "скушаешь использванную жвачку?":
                if ответ == "да":
                    print("ФУ БЛЯТЬ, ну ты и мерзость ходячая, чужие слюни доедаешь 🤢\n")
                else:
                    print("Да ладно тебе, под столом в падике отлепи и сожри, никто не увидит.\n")

            # 13. Пробовал мыться
            elif случайный_вопрос == "пробвал мытся":
                if ответ == "да":
                    print("тогда хули от тебя так говном несет 🤢\n")
                else:
                    print("по тебе видно 😏\n")

            print("-" * 40 + "\n")
                
        else:
            print("\n эй ты умственноотсталое существо, мозгов") 
            print("\n нету совсем? В чем проблема написать да или нет?\n")

# Вызываем функцию
игра_перевертыш()
