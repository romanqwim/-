class Vopros:
    def __init__(self, text: str, otvet_da: str, otvet_net: str,
                 otvet_mozhet: str = "", otvet_neznayu: str = "",
                 prodolzhenie: bool = False, kontrakt: bool = False):
        self.text = text
        self.otvet_da = otvet_da
        self.otvet_net = otvet_net
        self.otvet_mozhet = otvet_mozhet or "🤔 Может быть? Может быть ты просто боишься правды. Трус. 🐔"
        self.otvet_neznayu = otvet_neznayu or "🤷 Не знаешь? А кто знает? Ты вообще о чем-нибудь знаешь? 😂"
        self.prodolzhenie = prodolzhenie
        self.kontrakt = kontrakt

    def get_answer(self, answer: str) -> str:
        if answer == "да":
            return self.otvet_da
        elif answer == "нет":
            return self.otvet_net
        elif answer == "может быть":
            return self.otvet_mozhet
        elif answer == "не знаю":
            return self.otvet_neznayu
        return "🤖 Ты ебанутый? Я такого ответа не знаю."


