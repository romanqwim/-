def handle_iq_continuation(original_answer: str) -> str:
    if original_answer == "нет":
        answer = input("\n😏 Значит ещё ниже? (да/нет/может быть/не знаю): ").lower().strip()
        if answer == "да":
            return "\n❄️ Ну вот. Сам признался. Температура твоего мозга - абсолютный ноль. Где твой Нобелевский? Ах да, его не дают за бесполезность. 😂\n"
        elif answer == "нет":
            return "\n🌡️ Отрицание - первая стадия принятия. У тебя там градусник сломался или мозги просто замёрзли? 😏\n"
        elif answer == "может быть":
            return "\n🤔 Может быть? Ну ты уже на правильном пути - сомневаться в своей тупости. Но мы-то знаем правду. 😂\n"
        elif answer == "не знаю":
            return "\n🤷 Не знаешь? А кто тогда знает? Твои шарики для пинг-понга? Они уже сбежали. 🏃\n"
        else:
            return "\n🤡 Даже тут нормально ответить не можешь. Ты бы ещё калькулятор для ответа использовал. 🧮\n"
    return ""


